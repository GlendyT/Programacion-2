-- Ejecutar este script conectado al mismo esquema donde existe VEHICULO.
-- La llave foranea establece la relacion: un VEHICULO puede tener varias LLANTAS.

-- PASO 1: estas consultas deben devolver cero filas antes de crear la llave primaria.
-- Si aparecen resultados, primero hay que corregir los ID duplicados o nulos.
SELECT ID_VEHICULO, COUNT(*) AS CANTIDAD
FROM VEHICULO
GROUP BY ID_VEHICULO
HAVING COUNT(*) > 1;

SELECT *
FROM VEHICULO
WHERE ID_VEHICULO IS NULL;

-- PASO 2: ID_VEHICULO debe ser PRIMARY KEY o UNIQUE para que una llave
-- foranea pueda apuntar a esa columna. Este era el origen del ORA-02270.
ALTER TABLE VEHICULO
    ADD CONSTRAINT PK_VEHICULO PRIMARY KEY (ID_VEHICULO);

-- PASO 3: crear la tabla hija.

CREATE TABLE LLANTAS (
    ID_LLANTA   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_VEHICULO NUMBER NOT NULL,
    MARCA       VARCHAR2(50) NOT NULL,
    TAMANIO     NUMBER(3) NOT NULL,
    PRESION     NUMBER(6,2) NOT NULL,
    CONSTRAINT PK_LLANTAS PRIMARY KEY (ID_LLANTA),
    CONSTRAINT FK_LLANTAS_VEHICULO FOREIGN KEY (ID_VEHICULO)
        REFERENCES VEHICULO (ID_VEHICULO),
    CONSTRAINT CK_LLANTAS_TAMANIO CHECK (TAMANIO > 0),
    CONSTRAINT CK_LLANTAS_PRESION CHECK (PRESION > 0)
);

CREATE INDEX IDX_LLANTAS_ID_VEHICULO ON LLANTAS (ID_VEHICULO);

COMMIT;

-- CONSULTAR UN VEHICULO Y TODAS SUS LLANTAS POR ID
-- Cambiar el numero 1 por el ID_VEHICULO que se desea consultar.
SELECT
    v.ID_VEHICULO,
    v.MARCA AS MARCA_VEHICULO,
    v.MODELO,
    v.ANIO,
    v.COLOR,
    v.PRECIO,
    l.ID_LLANTA,
    l.MARCA AS MARCA_LLANTA,
    l.TAMANIO,
    l.PRESION
FROM VEHICULO v
LEFT JOIN LLANTAS l
    ON l.ID_VEHICULO = v.ID_VEHICULO
WHERE v.ID_VEHICULO = 1
ORDER BY l.ID_LLANTA;
